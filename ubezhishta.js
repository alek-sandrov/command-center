function mapsSearchUrl(address) {
    const query = address.startsWith('гр.') ? address : 'София, ' + address;
    return 'https://www.google.com/maps/search/?api=1&query=' + encodeURIComponent(query);
}

const container = document.getElementById('shelter-list');
const districts = [...new Set(SHELTERS.map(s => s[2]))].sort((a, b) => a.localeCompare(b, 'bg'));

districts.forEach(district => {
    const heading = document.createElement('div');
    heading.className = 'section-letter';
    heading.textContent = 'Район ' + district;
    container.appendChild(heading);

    const grid = document.createElement('div');
    grid.className = 'shelter-grid';
    SHELTERS.filter(s => s[2] === district).forEach(([name, address, , kind, operator, category]) => {
        const card = document.createElement('div');
        card.className = 'shelter-item';
        card.innerHTML = `
            <span class="shelter-kind ${kind === 'ПРУ' ? 'pru' : ''}">${kind === 'ПРУ' ? 'Противорадиационно укритие' : 'Скривалище'}</span>
            <div class="shelter-name">${name}</div>
            <div class="shelter-address">📍 ${address}</div>
            <div class="shelter-meta">${operator} · категория ${category}</div>
            <a class="shelter-map" href="${mapsSearchUrl(address)}" target="_blank" rel="noopener">🗺️ Карта</a>`;
        grid.appendChild(card);
    });
    container.appendChild(grid);
});
